import type { DesignSettings } from '../types'

export function generateGuide(settings: DesignSettings): string {
  const { colors, font, textSize } = settings
  return `# Shopify テーマ設定ガイド（Dawn テーマ想定）

このガイドでは、Shopify 管理画面から「配色」「フォント」「テキストサイズ」を反映する手順を説明します。
対象テーマ: **Dawn**（デフォルトテーマ）。他テーマの場合は項目名が異なる場合があります。

---

## 1. テーマカスタマイザーを開く

1. Shopify 管理画面にログインする
2. 左メニューで **「オンラインストア」** → **「テーマ」** をクリック
3. カスタマイズしたいテーマの **「カスタマイズ」** ボタンをクリック
4. テーマエディタ（カスタマイザー）が開きます

---

## 2. 配色を設定する

1. 左サイドバーで **「テーマの設定」**（歯車アイコン）をクリック
2. **「カラー」** または **「Colors」** をクリック
3. 次のように設定します（項目名はテーマにより「ベース」「メイン」など表記が異なる場合があります）:

| 設定項目の例 | 推奨値（HEX） | 用途の目安 |
|-------------|---------------|------------|
| メイン（Primary） | \`${colors.primary}\` | ボタン・リンクなど |
| サブ（Secondary） | \`${colors.secondary}\` | サブ要素 |
| 背景（Background） | \`${colors.background}\` | ページ背景 |
| テキスト（Text） | \`${colors.text}\` | 本文 |
| アクセント（Accent） | \`${colors.accent}\` | 強調・CTA |

4. 各色の **「色を選択」** をクリックし、上記の HEX コードを入力するか、カラーピッカーで合わせてください。
5. 右上の **「保存」** をクリック

---

## 3. フォントを設定する

1. 左サイドバーで **「テーマの設定」** → **「タイポグラフィ」** または **「Typography」** をクリック
2. 次のように設定します:

| 設定項目 | 推奨フォント |
|----------|--------------|
| 見出し（Heading） | **${font.heading}** |
| 本文（Body） | **${font.body}** |

3. フォントが一覧にない場合は、**「その他のフォントを追加」** から Google Fonts などで検索して追加できます。
4. 右上の **「保存」** をクリック

---

## 4. テキストサイズを調整する（該当する場合）

Dawn テーマでは、タイポグラフィ内に「見出しのサイズ」「本文のサイズ」などのスライダーがある場合があります。

| 項目の例 | 推奨値 |
|----------|--------|
| 本文のベースサイズ | **${textSize.base}px** 前後 |
| 見出しのサイズ | **${textSize.heading}px** 前後 |
| 小さいテキスト | **${textSize.small}px** 前後 |

スライダーや数値入力で上記に近い値に調整し、**「保存」** をクリックしてください。

---

## 5. 反映の確認

1. エディタ上部の **「プレビュー」** で、実機や別ウィンドウでの表示を確認できます。
2. 問題なければ **「保存」** で確定してください。
3. 本番ストアに反映されます。

---

## 設定値のまとめ（コピー用）

\`\`\`
【配色】
Primary:   ${colors.primary}
Secondary: ${colors.secondary}
Background: ${colors.background}
Text:      ${colors.text}
Accent:    ${colors.accent}

【フォント】
見出し: ${font.heading}
本文:   ${font.body}

【テキストサイズ】
ベース: ${textSize.base}px
見出し: ${textSize.heading}px
小:     ${textSize.small}px
\`\`\`

---
*このガイドは Shopify Design Helper により生成されました。テーマのバージョンにより項目名が異なる場合があります。*
`
}
